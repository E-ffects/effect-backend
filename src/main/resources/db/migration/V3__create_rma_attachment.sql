CREATE TABLE app.attachment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rma_id        TEXT NOT NULL REFERENCES app.intake (rma_id),
    kind          TEXT NOT NULL CHECK (kind IN ('RAW', 'OTHER')),
    file_name     TEXT NOT NULL,
    content_type  TEXT NOT NULL,
    size          BIGINT NOT NULL CHECK (size >= 0),
    storage_path  TEXT NOT NULL UNIQUE,
    uploaded_by   BIGINT NOT NULL,
    uploaded_at   TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX ux_attachment_raw_per_rma ON app.attachment (rma_id) WHERE kind = 'RAW';
CREATE INDEX ix_attachment_rma_id ON app.attachment (rma_id);

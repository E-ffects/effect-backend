CREATE TABLE app.pattern_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pattern_id TEXT NOT NULL,
    scope_from DATE NOT NULL,
    scope_to DATE NOT NULL,
    product TEXT NOT NULL DEFAULT '',
    title TEXT NOT NULL,
    generated_by BIGINT NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL,
    content JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (scope_from <= scope_to),
    UNIQUE (pattern_id, scope_from, scope_to, product)
);

CREATE INDEX ix_pattern_report_history ON app.pattern_report (generated_at DESC, id DESC);
CREATE INDEX ix_pattern_report_pattern_history ON app.pattern_report (pattern_id, generated_at DESC, id DESC);

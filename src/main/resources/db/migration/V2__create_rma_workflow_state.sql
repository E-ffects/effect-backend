CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE app.intake (
    rma_id                    TEXT PRIMARY KEY,
    intake_state              TEXT NOT NULL,
    customer_request          TEXT,
    follow_up_questions_json  JSONB,
    triage_proposal_json       JSONB,
    error_code                TEXT,
    created_by                BIGINT NOT NULL,
    created_at                TIMESTAMPTZ NOT NULL,
    updated_at                TIMESTAMPTZ NOT NULL
);

CREATE TABLE app.ai_analysis (
    analysis_id        TEXT PRIMARY KEY,
    rma_id             TEXT NOT NULL,
    mode               TEXT NOT NULL,
    analysis_state     TEXT NOT NULL,
    as_of              TIMESTAMPTZ,
    progress_json      JSONB,
    result_json        JSONB,
    trace_json         JSONB,
    warnings_json      JSONB,
    error_json         JSONB,
    langsmith_run_id   TEXT,
    created_at         TIMESTAMPTZ NOT NULL,
    completed_at       TIMESTAMPTZ
);

CREATE INDEX ix_ai_analysis_rma_latest
    ON app.ai_analysis (rma_id, created_at DESC, analysis_id DESC);

CREATE TABLE app.cause_decision (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rma_id             TEXT NOT NULL,
    analysis_id        TEXT NOT NULL UNIQUE REFERENCES app.ai_analysis (analysis_id),
    approval_status    TEXT NOT NULL,
    analysis_level     TEXT NOT NULL,
    candidates_json    JSONB,
    comment            TEXT,
    decided_by         TEXT,
    decided_at         TIMESTAMPTZ,
    refresh_status     TEXT,
    refresh_attempts   INTEGER NOT NULL DEFAULT 0
);
